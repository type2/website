#!/bin/sh
# deploybase build step: publish-ready transform of repo root into out/
# 1. copy tree, dereferencing symlinks (bartnik, m-codes, rescue, ... become real dirs)
# 2. rename extensionless html files -> *.html (clean URLs serve them as text/html)
# 3. append slash-form -> clean-form redirects to _redirects
set -e

mkdir -p out
tar -ch --exclude=./.git --exclude=./out -cf - . | tar -xf - -C out
cd out

rm -f _headers build-static.sh rename-list.txt statichost.yml
rm -rf scripts

while IFS= read -r p; do
  [ -n "$p" ] || continue
  if [ -f "$p" ]; then
    mv "$p" "$p.html"
  fi
done < ../rename-list.txt

{
  echo "# extensionless -> clean-url redirects (generated by build-static.sh)"
  while IFS= read -r p; do
    [ -n "$p" ] || continue
    enc=$(printf '%s' "$p" | sed 's/ /%20/g')
    printf '/%s/\t/%s\t301\n' "$enc" "$enc"
  done < ../rename-list.txt
} >> _redirects

echo "build-static: done. redirects: $(wc -l < _redirects) lines, renamed: $(grep -c 'html$' ../rename-list.txt) target files"
